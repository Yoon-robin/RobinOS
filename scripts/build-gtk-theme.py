#!/usr/bin/env python3
"""Builds the GTK colours of RobinOS from the shell's tokens (desktop/shell/Theme.qml).

GTK apps (Files, Firefox, Text Editor, ...) otherwise keep GNOME's grey faces and
GNOME blue. Both GTK 3 (adw-gtk3) and libadwaita read the same named colours
(window_bg_color, accent_bg_color, ...), so one table maps them to kit tokens:

  desktop/gtk/libadwaita.css   GTK 4 / libadwaita, light with a dark media query
                               (follows the colour scheme live); every user's
                               ~/.config/gtk-4.0/gtk.css imports it (Theme.qml)
  desktop/gtk/themes/RobinOS[-dark]/gtk-3.0/gtk.css
                               GTK 3 themes: adw-gtk3 plus the same colours; the
                               shell sets gtk-theme to one of them
  desktop/gtk/gtksourceview/robinos[-dark].xml
                               Text Editor's style scheme (it paints its window
                               from the scheme); dconf picks "robinos"
  desktop/gtk/firefox.css      Firefox's toolbars, panels and new tab page: it
                               draws its own grey, not the GTK colours, so its
                               autoconfig (desktop/firefox/robinos.cfg) registers
                               this as a user sheet; light-dark() follows the scheme

Run after changing a colour in Theme.qml; --check (scripts/check.sh) fails when the
files are stale:

    python3 scripts/build-gtk-theme.py [--check]
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
THEME = ROOT / "desktop/shell/Theme.qml"
OUT = ROOT / "desktop/gtk"

# libadwaita / adw-gtk3 named colour -> Theme.qml token. The kit has no green or
# yellow: success is the blue, warning is the apricot note.
COLOURS = [
    ("window_bg_color", "bg"), ("window_fg_color", "fg"),
    ("view_bg_color", "bg"), ("view_fg_color", "fg"),
    ("headerbar_bg_color", "side"), ("headerbar_fg_color", "fg"),
    ("headerbar_backdrop_color", "side"), ("headerbar_shade_color", "border"),
    ("sidebar_bg_color", "side"), ("sidebar_fg_color", "fg"),
    ("sidebar_backdrop_color", "side"), ("sidebar_border_color", "border"),
    ("sidebar_shade_color", "border"),
    ("secondary_sidebar_bg_color", "surface"), ("secondary_sidebar_fg_color", "fg"),
    ("secondary_sidebar_backdrop_color", "surface"), ("secondary_sidebar_border_color", "border"),
    ("secondary_sidebar_shade_color", "border"),
    ("card_bg_color", "surface"), ("card_fg_color", "fg"), ("card_shade_color", "border"),
    ("dialog_bg_color", "bg"), ("dialog_fg_color", "fg"),
    ("popover_bg_color", "panel"), ("popover_fg_color", "fg"),
    ("thumbnail_bg_color", "surface"), ("thumbnail_fg_color", "fg"),
    ("accent_bg_color", "primary"), ("accent_fg_color", "primaryFg"), ("accent_color", "accent"),
    ("destructive_bg_color", "destructiveSolid"), ("destructive_fg_color", "primaryFg"),
    ("destructive_color", "destructive"),
    ("success_bg_color", "primary"), ("success_fg_color", "primaryFg"), ("success_color", "accent"),
    ("warning_bg_color", "note"), ("warning_fg_color", "primaryFg"), ("warning_color", "note"),
    ("error_bg_color", "destructiveSolid"), ("error_fg_color", "primaryFg"),
    ("error_color", "destructive"),
]
# The kit's window corner (Theme.radiusLg); Hyprland rounds windows the same
WINDOW_RADIUS = "14px"


def tokens():
    """name -> (dark, light) for every plain colour property in Theme.qml."""
    found = {}
    prop = re.compile(r'readonly property color (\w+): (.*)$')
    pair = re.compile(r'dark \? "(#[0-9a-fA-F]{6})" : "(#[0-9a-fA-F]{6})"')
    single = re.compile(r'^"(#[0-9a-fA-F]{6})"$')
    for line in THEME.read_text(encoding="utf-8").splitlines():
        m = prop.search(line.strip())
        if not m:
            continue
        name, value = m.groups()
        pairs = pair.findall(value)
        if pairs:
            # "highContrast ? hcLine : (dark ? a : b)": the last pair is the normal look
            found[name] = tuple(c.lower() for c in pairs[-1])
        elif single.match(value):
            found[name] = (value.strip('"').lower(),) * 2
    return found


def block(values, which, indent=""):
    return "".join(f"{indent}@define-color {name} {values[token][which]};\n" for name, token in COLOURS)


HEAD = "/* Generated by scripts/build-gtk-theme.py from desktop/shell/Theme.qml. Do not edit. */\n"

# GtkSourceView editor faces -> Theme.qml tokens. Text Editor colours its whole
# window from the style scheme, not from the GTK colours above. The syntax colours
# stay Adwaita's (parent-scheme): like the terminal's ANSI colours they carry the
# program's meaning.
SOURCE_STYLES = [
    ("text", {"background": "bg", "foreground": "fg"}),
    ("background-pattern", {"background": "side"}),
    ("current-line", {"background": "surface"}),
    ("current-line-number", {"background": "surface", "foreground": "muted"}),
    ("line-numbers", {"background": "bg", "foreground": "subtle"}),
    ("cursor", {"foreground": "fg"}),
    ("right-margin", {"background": "border", "foreground": "border"}),
    ("draw-spaces", {"foreground": "borderStrong"}),
]


def source_scheme(values, which, scheme, other):
    dark = scheme.endswith("-dark")
    styles = "".join(
        f'  <style name="{name}" '
        + " ".join(f'{attr}="{values[token][which]}"' for attr, token in attrs.items())
        + "/>\n"
        for name, attrs in SOURCE_STYLES
    )
    return (
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        "<!-- Generated by scripts/build-gtk-theme.py from desktop/shell/Theme.qml. Do not edit. -->\n"
        f'<style-scheme id="{scheme}" name="RobinOS{" Dark" if dark else ""}" version="1.0"'
        f' parent-scheme="{"Adwaita-dark" if dark else "Adwaita"}">\n'
        "  <author>RobinOS</author>\n"
        "  <description>robin-ui V5 faces for Text Editor</description>\n"
        "  <metadata>\n"
        f'    <property name="variant">{"dark" if dark else "light"}</property>\n'
        f'    <property name="{"light" if dark else "dark"}-variant">{other}</property>\n'
        "  </metadata>\n"
        + styles
        + "</style-scheme>\n"
    )


# Firefox's chrome variables (browser-colors.css, tokens-shared.css in omni.ja,
# Firefox 160) -> Theme.qml tokens: the tab strip is the side column, the toolbar
# and the selected tab the page, the address field a control
FIREFOX_CHROME = [
    ("--toolbox-background-color", "side"), ("--toolbox-background-color-inactive", "side"),
    ("--toolbox-text-color", "fg"), ("--toolbox-text-color-inactive", "muted"),
    ("--toolbar-background-color", "bg"), ("--toolbar-text-color", "fg"),
    ("--tab-background-color-selected", "bg"), ("--tabpanel-background-color", "bg"),
    ("--toolbar-field-background-color", "raised"), ("--toolbar-field-text-color", "fg"),
    ("--toolbar-field-border-color", "border"),
    ("--toolbar-field-background-color-focus", "bg"), ("--toolbar-field-text-color-focus", "fg"),
    ("--toolbar-field-border-color-focus", "accent"),
    ("--chrome-content-separator-color", "border"),
    ("--panel-background-color", "panel"), ("--panel-text-color", "fg"),
    ("--panel-border-color", "panelBorder"),
    ("--color-accent-primary", "accent"), ("--color-accent-primary-hover", "primaryHover"),
    ("--color-accent-primary-active", "primary"),
    ("--button-background-color-primary", "primary"),
    ("--button-background-color-primary-hover", "primaryHover"),
    ("--button-background-color-primary-active", "primary"),
    ("--button-text-color-primary", "primaryFg"), ("--button-text-color-primary-hover", "primaryFg"),
    ("--button-text-color-primary-active", "primaryFg"),
    ("--focus-outline-color", "accent"), ("--link-color", "accent"),
]
# The new tab and home pages (activity-stream.css)
FIREFOX_NEWTAB = [
    ("--newtab-background-color", "bg"), ("--newtab-background-color-secondary", "surface"),
    ("--newtab-text-primary-color", "fg"), ("--background-color-canvas", "bg"),
    ("--background-color-box", "surface"), ("--text-color", "fg"),
    ("--newtab-primary-action-background", "primary"),
    ("--newtab-primary-action-background-pocket", "primary"),
    ("--newtab-status-success", "accent"),
]
# Every Firefox page (about:preferences, about:addons, ...): its violet accent and
# filled buttons become the kit's one blue
FIREFOX_PAGES = [
    ("--color-accent-primary", "accent"), ("--color-accent-primary-hover", "primaryHover"),
    ("--color-accent-primary-active", "primary"),
    ("--button-background-color-primary", "primary"),
    ("--button-background-color-primary-hover", "primaryHover"),
    ("--button-background-color-primary-active", "primary"),
    ("--button-text-color-primary", "primaryFg"),
    ("--focus-outline-color", "accent"), ("--link-color", "accent"),
]


def firefox_css(values):
    def decls(table):
        return "".join(
            f"    {name}: light-dark({values[token][1]}, {values[token][0]}) !important;\n"
            for name, token in table
        )
    return (
        HEAD
        + "/* Firefox in the kit's faces. Firefox draws its toolbars in its own grey, not the\n"
        + "   GTK colours, and an unsigned theme can't be installed, so its autoconfig\n"
        + "   (desktop/firefox/robinos.cfg) registers this file as a user sheet. Only\n"
        + "   Firefox's own pages are touched; light-dark() follows the colour scheme. */\n"
        + '@-moz-document url("chrome://browser/content/browser.xhtml") {\n'
        + "  :root {\n" + decls(FIREFOX_CHROME) + "  }\n}\n\n"
        + '@-moz-document url-prefix("about:") {\n'
        + "  :root {\n" + decls(FIREFOX_PAGES) + "  }\n}\n\n"
        + '@-moz-document url-prefix("about:newtab"), url-prefix("about:home") {\n'
        + "  :root {\n" + decls(FIREFOX_NEWTAB) + "  }\n}\n"
    )


def outputs():
    values = tokens()
    used = COLOURS + FIREFOX_CHROME + FIREFOX_NEWTAB + FIREFOX_PAGES
    missing = sorted({t for _, t in used} - values.keys())
    if missing:
        sys.exit(f"build-gtk-theme: Theme.qml has no colour {', '.join(missing)}")
    dark, light = 0, 1
    files = {}
    files["libadwaita.css"] = (
        HEAD
        + "/* GTK 4 and libadwaita: the kit's faces, one blue, no green or yellow. Light first,\n"
        + "   dark in the media query libadwaita itself uses, so open apps follow the shell's\n"
        + "   theme switch without restarting. */\n"
        + block(values, light)
        + "\n@media (prefers-color-scheme: dark) {\n"
        + block(values, dark, "  ")
        + "}\n\n"
        + f":root {{ --window-radius: {WINDOW_RADIUS}; }}\n"
    )
    files["firefox.css"] = firefox_css(values)
    for theme, base, which in (("RobinOS", "adw-gtk3", light), ("RobinOS-dark", "adw-gtk3-dark", dark)):
        files[f"themes/{theme}/gtk-3.0/gtk.css"] = (
            HEAD
            + f"/* GTK 3 (Firefox, ...): {base} with the kit's colours */\n"
            + f'@import url("../../{base}/gtk-3.0/gtk.css");\n\n'
            + block(values, which)
        )
        scheme = "robinos-dark" if which == dark else "robinos"
        other = "robinos" if which == dark else "robinos-dark"
        files[f"gtksourceview/{scheme}.xml"] = source_scheme(values, which, scheme, other)
        files[f"themes/{theme}/index.theme"] = (
            "[Desktop Entry]\n"
            "Type=X-GNOME-Metatheme\n"
            f"Name={theme}\n"
            f"Comment=RobinOS colours on {base} (scripts/build-gtk-theme.py)\n"
            "Encoding=UTF-8\n\n"
            "[X-GNOME-Metatheme]\n"
            f"GtkTheme={theme}\n"
        )
    return files


def main():
    check = "--check" in sys.argv[1:]
    stale = []
    for rel, text in outputs().items():
        path = OUT / rel
        if check:
            if not path.is_file() or path.read_text(encoding="utf-8") != text:
                stale.append(str(path.relative_to(ROOT)))
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8", newline="\n")
        print(path.relative_to(ROOT))
    if stale:
        sys.exit("build-gtk-theme: stale, run python3 scripts/build-gtk-theme.py: " + ", ".join(stale))
    if check:
        print("build-gtk-theme: desktop/gtk matches Theme.qml")


if __name__ == "__main__":
    main()
